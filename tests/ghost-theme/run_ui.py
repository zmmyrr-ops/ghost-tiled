#!/usr/bin/env python3
"""Real GUI callback regression. Use a disposable test app, not an editor in use.

Temporarily installs a test extension beside the supplied macOS app's bundled
extensions, launches a separate instance (offscreen by default), and cleans up on exit.
"""
import argparse,json,os,subprocess,tempfile,time
from pathlib import Path
p=argparse.ArgumentParser()
p.add_argument('--tiled',type=Path,required=True)
p.add_argument('--config-root',type=Path,required=True)
p.add_argument('--platform',default='offscreen',choices=['offscreen','cocoa'])
p.add_argument('--map',type=Path,required=True,help='Output generated by run.py')
a=p.parse_args();binary=a.tiled.resolve();root=a.config_root.resolve();source=a.map.resolve()
plugin=Path(__file__).resolve().parents[2]/'src/tiled/extensions/ghost-theme/ghost-theme.js'
extensions=binary.parent.parent/'Resources/extensions'
if not extensions.is_dir():raise SystemExit('Use an isolated macOS Tiled.app test build')
tmp=tempfile.TemporaryDirectory(prefix='zzz-theme-ui-test-',dir=extensions)
folder=Path(tmp.name);marker=folder/'result.txt'
instrumented=plugin.read_text().replace('var tabs=[', 'var tabs=ThemeTest.tabs=[').replace('var pages=[[],[]]', 'var pages=ThemeTest.pages=[[],[]]').replace('var b=widget(d.addButton(text));', 'var b=widget(d.addButton(text));ThemeTest.buttons[text]=b;').replace("adjustments=widget(d.addCheckBox('展开单项调整',false))", "adjustments=ThemeTest.adjustments=widget(d.addCheckBox('展开单项调整',false))")
code='var GhostThemeHeadless=true,ThemeTest={buttons:{}};\n'+instrumented+'\nGhostTheme.setResourceRoot('+json.dumps(str(root))+');\n'
code+='''
tiled.assetOpened.connect(function(map){
 if(!map.isTileMap||map.fileName!==TEST_MAP)return;
 var result='';
 function assert(ok,text){if(!ok)throw new Error(text);}
 try{
  tiled.activeAsset=map;var panel=GhostTheme.openPanel();
  function find(name){return map.layers.filter(function(l){return l.name===name;})[0];}
  var leaves=find('GhostTheme_RoomLeaves').objectCount;
  assert(leaves>0,'test map needs autumn leaves');
  ThemeTest.tabs[0].click();
  assert(ThemeTest.tabs[0].checked&&!ThemeTest.tabs[1].checked,'original tab not selected');
  assert(ThemeTest.pages[0].every(function(w){return w.visible;})&&ThemeTest.pages[1].every(function(w){return !w.visible;}),'autumn controls or labels leaked into original page');
  assert(map.property('ghost.mapTheme')==='autumn'&&find('GhostTheme_RoomLeaves').objectCount===leaves,'browsing tabs modified map');
  ThemeTest.buttons['应用原始主题'].click();
  assert(map.property('ghost.mapTheme')==='original','original apply button failed');
  ['Edges','Scatter','RoomLeaves','Grass'].forEach(function(s){assert(find('GhostTheme_'+s).objectCount===0,'original contains autumn '+s);});
  assert(!find('GhostTheme_Props').visible,'autumn equipment visible on original map');
  tiled.trigger('Undo');
  assert(map.property('ghost.mapTheme')==='autumn'&&find('GhostTheme_RoomLeaves').objectCount===leaves&&find('GhostTheme_Props').visible,'theme switch undo did not restore autumn');
  ThemeTest.tabs[1].click();
  assert(!ThemeTest.tabs[0].checked&&ThemeTest.tabs[1].checked,'autumn tab not selected');
  assert(!ThemeTest.buttons['生成落叶堆'].visible,'advanced options should start collapsed');
  ThemeTest.adjustments.click();
  assert(ThemeTest.pages[0].every(function(w){return !w.visible;})&&ThemeTest.pages[1].every(function(w){return w.visible;}),'theme pages are not exclusive');
  ThemeTest.tabs[0].click();assert(ThemeTest.pages[1].every(function(w){return !w.visible;}),'expanded controls leaked into original');ThemeTest.tabs[1].click();ThemeTest.adjustments.click();
  map.currentLayer=map.layers.filter(function(l){return l.name==='Ground';})[0];
  var tool=GhostTheme.beginPlacement(map,21,.75);
  tool.keyPressed(Qt.Key_Escape,0);assert(tiled.mapEditor.selectedTool!==tiled.mapEditor.tool('GhostTheme_PlaceProp'),'escape before first click failed');
  tool=GhostTheme.beginPlacement(map,21,.75);
  assert(tiled.mapEditor.selectedTool===tiled.mapEditor.tool('GhostTheme_PlaceProp'),'tool not active');
  tool.mouseMoved(1400,900,0);
  assert(tool.preview.layerCount===1,'no hover sprite: '+tool.statusInfo+' map='+tool.map.fileName);
  var props=map.layers.filter(function(l){return l.name==='GhostTheme_Props';})[0],n=props.objectCount;
  tool.mousePressed(Qt.LeftButton,1400,900,0);
  assert(props.objectCount===n+1,'first click failed: '+tool.statusInfo);
  assert(tiled.mapEditor.selectedTool===tiled.mapEditor.tool('ObjectSelectionTool'),'placement did not return to selection');
  assert(tool.preview.layerCount===0,'preview remains after placement');
  assert(map.selectedObjects.length===1&&map.selectedObjects[0]===props.objectAt(n),'placed device not selected');
  tool.mousePressed(Qt.LeftButton,1700,900,0);assert(props.objectCount===n+1,'second click placed another device');
  tool=GhostTheme.beginPlacement(map,21,.75);
  tool.mousePressed(Qt.LeftButton,-50,-50,0);assert(props.objectCount===n+2,'outside-map placement blocked: '+tool.statusInfo);
  assert(props.objectAt(n+1).x<0&&props.objectAt(n+1).y<0,'outside-map position clamped');
  assert(tiled.mapEditor.selectedTool===tiled.mapEditor.tool('ObjectSelectionTool'),'outside-map placement did not stop');
  tiled.trigger('Undo');assert(props.objectCount===n+1,'outside-map placement undo failed');
  tool=GhostTheme.beginPlacement(map,21,.75);
  tool.mouseMoved(1400,900,0);tool.keyPressed(Qt.Key_H,0);tool.mousePressed(Qt.LeftButton,1400,900,0);
  assert(props.objectCount===n+2&&props.objectAt(n+1).tileFlippedHorizontally,'overlapping mirrored placement blocked');
  assert(tiled.mapEditor.selectedTool===tiled.mapEditor.tool('ObjectSelectionTool'),'second placement did not stop');
  tiled.trigger('Undo');assert(props.objectCount===n+1,'undo failed');tiled.trigger('Redo');assert(props.objectCount===n+2,'redo failed');
  tool=GhostTheme.beginPlacement(map,21,.75);
  tool.keyPressed(Qt.Key_Escape,0);assert(tiled.mapEditor.selectedTool!==tiled.mapEditor.tool('GhostTheme_PlaceProp'),'escape did not stop');
  // Rectangular crops participate in the same undo transaction as theme switching.
  map.resize({width:60,height:30});
  var oldBackground=find('GhostTheme_Base').objectAt(0),oldTile=oldBackground.tile,oldWidth=oldBackground.width;
  GhostTheme.applyTheme(map);
  var croppedTile=oldBackground.tile;
  assert(croppedTile!==oldTile&&croppedTile.imageRect.height===2400&&oldBackground.width===6000,'wide crop not applied');
  tiled.trigger('Undo');assert(oldBackground.tile===oldTile&&oldBackground.width===oldWidth,'crop undo failed');
  tiled.trigger('Redo');assert(oldBackground.tile.imageRect.height===2400&&oldBackground.width===6000,'crop redo failed');
  GhostTheme.applyOriginalTheme(map);assert(!find('GhostTheme_Base').visible,'cropped background remains in original');
  tiled.trigger('Undo');assert(find('GhostTheme_Base').visible&&oldBackground.tile.imageRect.height===2400,'original undo lost crop');
  result='GUI_TEST_OK exclusive theme pages, browse without mutation, original cleanup, theme undo, single placement, auto-stop, selection, repeat-click ignored, flip, outside-map placement, overlapping devices, undo/redo, cancel, rectangular background undo/redo; panel height='+panel.height;panel.accept();
 }catch(e){result='FAIL '+e.message+'\\n'+e.stack;}
 var f=new TextFile(MARKER,TextFile.WriteOnly);f.write(result);f.commit();
});
'''.replace('MARKER',json.dumps(str(marker))).replace('TEST_MAP',json.dumps(str(source)))
(folder/'test.js').write_text(code)
try:
 with tempfile.TemporaryFile(mode='w+') as log:
  process=subprocess.Popen([str(binary),'--new-instance',str(source)],env=dict(os.environ,QT_QPA_PLATFORM=a.platform),stdout=log,stderr=log)
  try:
   deadline=time.monotonic()+15
   while not marker.exists() and process.poll() is None and time.monotonic()<deadline:time.sleep(.1)
   result=marker.read_text() if marker.exists() else 'FAIL no completion marker'
  finally:
   process.terminate()
   try:process.wait(timeout=5)
   except subprocess.TimeoutExpired:process.kill();process.wait()
  print(result)
  if not result.startswith('GUI_TEST_OK'):
   log.seek(0);print(log.read());raise SystemExit(1)
finally:tmp.cleanup()
